function makePolicy(
  id: string,
  leadId: string,
  vin: string,
  customerId: string,
  providerId: string,
  policyNumber: string,
  totalPremium: number,
  idv: number,
  commissionPct: number,
  advisorId: string,
  periodStart: string,
  periodEnd: string,
): IssuedPolicy {
  const commissionEarned = Math.round(totalPremium * commissionPct / 100);
  const commissionGst = Math.round(commissionEarned * 18 / 100);
  return {
    policyId: id,
    leadId,
    vin,
    customerId,
    providerId,
    policyNumber,
    policyType: 'comprehensive',
    totalPremium,
    idv,
    selectedAddons: ['zero-dep', 'rsa', 'engine-protect'],
    periodStart,
    periodEnd,
    docId: `doc-insurance-${id}`,
    commissionEarned,
    commissionGst,
    advisorId,
    issuedAt: `${periodStart}T10:00:00.000Z`,
    claimHistory: [],
  };
}

